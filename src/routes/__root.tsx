function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="pt">
      <head>
        <HeadContent />
      </head>
      <body className="min-h-dvh bg-background text-foreground font-sans antialiased overflow-x-hidden">
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const router = useRouter();

  useEffect(() => {
    const { data: sub } = supabase.auth.onAuthStateChange((event) => {
      if (event !== "SIGNED_IN" && event !== "SIGNED_OUT" && event !== "USER_UPDATED") return;
      router.invalidate();
      if (event !== "SIGNED_OUT") queryClient.invalidateQueries();
    });
    return () => sub.subscription.unsubscribe();
  }, [router, queryClient]);

  return (
    <QueryClientProvider client={queryClient}>
      {/* Mobile-first shell: trava largura em telas grandes */}
      <div className="mx-auto w-full max-w-md sm:max-w-3xl lg:max-w-6xl min-h-dvh">
        <Outlet />
      </div>
      <Toaster
        theme="light"
        position="top-center"
        offset="calc(env(safe-area-inset-top) + 0.5rem)"
        mobileOffset="calc(env(safe-area-inset-top) + 0.5rem)"
      />
    </QueryClientProvider>
  );
}
